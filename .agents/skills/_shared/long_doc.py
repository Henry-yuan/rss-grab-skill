"""跨 skill 共享：长文判定的单一口径（spec AC-A2）。

> ⚠️ **这是 rss-grab 仓库的一份独立实体拷贝，不是主项目的软链**（spec AC-C5）。
> 主项目 `.agents/skills/_shared/long_doc.py` 与本文件**必须手动双改 + 两边各跑测试**。
> 禁止用脚本单向覆盖 —— 那会抹掉本仓库的 rss-only 裁剪。
>
> 本模块是纯文本函数，**不引用任何具体源**，所以主项目版与本版逻辑完全一致，
> 差异只在文档措辞（主项目那份描述三源，本份只描述 rss）。若将来给本模块加了
> 源专属逻辑，请在那侧做裁剪，并在此处注明裁剪了什么。

## 为什么需要它

rss 原本用「原始字符 50,000」判长文，小红书用「净字 15,000」。
同样一篇 2 万净字的内容，rss 当短文、小红书当长文 —— 实测 48 篇 rss 里
**24 篇（正好一半）被当短文处理**，净字 15,000–25,000、原始字符 29,732–49,433，
全部卡在 50,000 线下方。统一到净字口径后这 24 篇改走长文路径。

## 净字的定义

1. 剥掉 ASR 段标记 `**[mm:ss]**`
2. 删掉所有空白字符

**第 1 步不能省**：ASR 转写里每段都带 `**[mm:ss]**`，一段约 9-10 字符。
一篇 5 小时的转写有上千段，时间戳本身能占到原文的一半 —— 不剥的话
「净字」虚高约 1 倍（实测十字路口 5 小时样本：207,326 vs 修正后 107,102）。

**分钟必须是 1-3 位**：历史实现写的是 `\\d{1,2}`，于是 `**[144:23]**`、
`**[163:45]**`、`**[240:00]**` 这类超过 100 分钟的标记全部剥不掉。
rss 48 篇里有 1 篇（十字路口 5 小时那篇，最大 325 分钟）命中，
共 8,352 处标记剥不掉。4 位分钟（1000+）不是合法 ASR 标记，按设计不匹配。
"""
import re

# 长文阈值（spec AC-A3，Henry 2026-10-03 拍板，采用小红书 v3 的定义）
LONG_DOC_THRESHOLD = 15_000

# ASR 段标记。分钟 1-3 位、秒固定 2 位；前后是 Markdown 粗体星号。
_TS_STRIP = re.compile(r"\*\*\[\d{1,3}:\d{2}\]\*\*")

# 裸时间戳（非粗体形态），用于宽松场景的清洗
_TS_BARE = re.compile(r"\[\d{1,3}:\d{2}(?::\d{2})?\]")

_WHITESPACE = re.compile(r"\s+")


def net_len(text: str) -> int:
    """净字数：剥 ASR 段标记 → 删所有空白。长文阈值判定的唯一口径。

    >>> net_len("**[00:12]** 你好 世界")
    4
    >>> net_len("**[144:23]** 内容")
    2
    """
    return len(_WHITESPACE.sub("", _TS_STRIP.sub("", text)))


def is_long_doc(text: str, threshold: int = LONG_DOC_THRESHOLD) -> bool:
    """是否按长文路径处理。

    用**严格大于**而非 `>=`：与小红书 `build_v3.py` 的 `n_chars > LONG_DOC_THRESHOLD`
    对齐，否则净字恰为 15000 的样本上 spec 与代码会给出相反判定（AC-A3）。
    """
    return net_len(text) > threshold


def strip_timestamps(text: str) -> str:
    """剥掉所有时间戳形态（粗体段标记 + 裸标记）。仅供源清洗用，不影响净字口径。"""
    return _TS_BARE.sub("", _TS_STRIP.sub("", text))
